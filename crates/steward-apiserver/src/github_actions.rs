pub fn validate_generated_github_actions_yaml(
    value: &str,
    request: &GithubActionsRenderRequest,
    context: &GithubActionsRenderContext,
) -> Result<(), GithubActionsRenderError> {
    if value.len() > 32 * 1024 {
        return Err(GithubActionsRenderError::InvalidGeneratedWorkflow);
    }
    let options = serde_saphyr::options! {
        budget: serde_saphyr::budget! {
            max_events: 1_000,
            max_aliases: 0,
            max_anchors: 0,
            max_depth: 16,
            max_inclusion_depth: 0,
            max_documents: 1,
            max_nodes: 500,
            max_total_scalar_bytes: 24 * 1024,
            max_total_comment_bytes: 4 * 1024,
            max_merge_keys: 0,
        },
        duplicate_keys: serde_saphyr::DuplicateKeyPolicy::Error,
        merge_keys: serde_saphyr::MergeKeyPolicy::Error,
        alias_limits: serde_saphyr::alias_limits! {
            max_total_replayed_events: 0,
            max_replay_stack_depth: 0,
            max_alias_expansions_per_anchor: 0,
        },
        strict_booleans: true,
        require_indent: serde_saphyr::RequireIndent::Even,
    };
    serde_saphyr::from_str_with_options::<serde_json::Value>(value, options)
        .map_err(|_| GithubActionsRenderError::InvalidGeneratedWorkflow)?;
    let expected = render_github_actions_workflow(request, context)?;
    if value != expected.yaml {
        return Err(GithubActionsRenderError::InvalidGeneratedWorkflow);
    }
    Ok(())
}

fn validate_request(
    request: &GithubActionsRenderRequest,
    context: &GithubActionsRenderContext,
) -> Result<(), GithubActionsRenderError> {
    if request.schema_version != GITHUB_ACTIONS_RENDER_REQUEST_SCHEMA {
        return Err(GithubActionsRenderError::UnsupportedSchema);
    }
    validate_envelope(&context.current_envelope)?;
    validate_release(&context.reviewed_release)?;
    if request.envelope != context.current_envelope {
        return Err(GithubActionsRenderError::StaleEnvelope);
    }
    if request.release != context.reviewed_release {
        return Err(GithubActionsRenderError::UnreviewedRelease);
    }
    if request.task_template.id != GITHUB_FILE_READ_TEMPLATE {
        return Err(GithubActionsRenderError::UnsupportedTemplate);
    }
    if !context
        .allowed_task_templates
        .iter()
        .any(|template| template == &request.task_template.id)
    {
        return Err(GithubActionsRenderError::UnsupportedEnvelopeAuthority);
    }
    let template = &request.task_template;
    if [
        template.repository.as_str(),
        template.path.as_str(),
        request.envelope.id.as_str(),
    ]
    .iter()
    .any(|value| secret_like(value))
    {
        return Err(GithubActionsRenderError::SecretLikeInput);
    }
    if !valid_repository(&template.repository) {
        return Err(GithubActionsRenderError::InvalidRepository);
    }
    if !valid_full_sha(&template.revision) {
        return Err(GithubActionsRenderError::InvalidRevision);
    }
    if !valid_path(&template.path) {
        return Err(GithubActionsRenderError::InvalidPath);
    }
    Ok(())
}

fn validate_envelope(
    envelope: &GithubActionsEnvelopeSelection,
) -> Result<(), GithubActionsRenderError> {
    if envelope.revision == 0
        || envelope.id.is_empty()
        || envelope.id.len() > 63
        || !envelope.id.chars().all(|character| {
            character.is_ascii_lowercase()
                || character.is_ascii_digit()
                || matches!(character, '-' | '_' | '.')
        })
        || !valid_digest(&envelope.digest)
    {
        return Err(GithubActionsRenderError::InvalidRequest);
    }
    Ok(())
}

fn validate_release(release: &StewardRunRelease) -> Result<(), GithubActionsRenderError> {
    if release.manifest_schema_version != 4
        || !valid_semver(&release.version)
        || !valid_full_sha(&release.workflow_commit)
        || !valid_full_sha(&release.action_commit)
        || !valid_immutable_image(&release.governed_job_container_image)
    {
        return Err(GithubActionsRenderError::UnreviewedRelease);
    }
    Ok(())
}

fn valid_semver(value: &str) -> bool {
    let parts: Vec<&str> = value.split('.').collect();
    parts.len() == 3
        && parts.iter().all(|part| {
            !part.is_empty()
                && part.chars().all(|character| character.is_ascii_digit())
                && (part == &"0" || !part.starts_with('0'))
        })
}

fn valid_full_sha(value: &str) -> bool {
    value.len() == 40
        && value
            .chars()
            .all(|character| character.is_ascii_digit() || ('a'..='f').contains(&character))
}

fn valid_digest(value: &str) -> bool {
    value.strip_prefix("sha256:").is_some_and(|digest| {
        digest.len() == 64
            && digest
                .chars()
                .all(|character| character.is_ascii_digit() || ('a'..='f').contains(&character))
    })
}

fn valid_immutable_image(value: &str) -> bool {
    let Some((repository, digest)) = value.split_once('@') else {
        return false;
    };
    !repository.is_empty()
        && !repository.contains(char::is_whitespace)
        && !repository.contains(':')
        && valid_digest(digest)
}

fn valid_repository(value: &str) -> bool {
    if value.is_empty() || value.len() > 200 {
        return false;
    }
    let parts: Vec<&str> = value.split('/').collect();
    parts.len() == 2 && parts.iter().all(|part| valid_repository_part(part))
}

fn valid_repository_part(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 100
        && value != "."
        && value != ".."
        && value.chars().all(|character| {
            character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.')
        })
}

fn valid_path(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 240
        && !value.starts_with('/')
        && !value.contains('\\')
        && value.split('/').all(|part| {
            !part.is_empty()
                && part != "."
                && part != ".."
                && part.chars().all(|character| {
                    character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.')
                })
        })
}

fn secret_like(value: &str) -> bool {
    let lowercase = value.to_ascii_lowercase();
    value.chars().any(char::is_control)
        || [
            "secret",
            "token",
            "password",
            "credential",
            "private-key",
            "private_key",
            "${{",
            "}}",
            "akia",
        ]
        .iter()
        .any(|marker| lowercase.contains(marker))
}


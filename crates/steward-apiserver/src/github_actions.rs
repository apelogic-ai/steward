#[derive(Clone, Debug, Eq, PartialEq)]
pub enum GithubActionsRenderError {
    InvalidRequest,
    UnsupportedSchema,
    StaleEnvelope,
    UnreviewedRelease,
    UnsupportedTemplate,
    UnsupportedEnvelopeAuthority,
    InvalidRepository,
    InvalidRevision,
    InvalidPath,
    SecretLikeInput,
    InvalidGeneratedWorkflow,
}

impl fmt::Display for GithubActionsRenderError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(match self {
            Self::InvalidRequest => "GitHub Actions render request is invalid",
            Self::UnsupportedSchema => "GitHub Actions render request schema is unsupported",
            Self::StaleEnvelope => "selected Steward envelope is stale",
            Self::UnreviewedRelease => "steward-run release is not the reviewed release",
            Self::UnsupportedTemplate => "GitHub Actions task template is unsupported",
            Self::UnsupportedEnvelopeAuthority => {
                "GitHub Actions task template is outside the selected envelope"
            }
            Self::InvalidRepository => "GitHub repository is invalid",
            Self::InvalidRevision => "GitHub revision is invalid",
            Self::InvalidPath => "GitHub path is invalid",
            Self::SecretLikeInput => "GitHub Actions request contains secret-like input",
            Self::InvalidGeneratedWorkflow => "generated GitHub Actions workflow is invalid",
        })
    }
}

impl Error for GithubActionsRenderError {}

pub fn parse_github_actions_render_request(
    value: &str,
) -> Result<GithubActionsRenderRequest, GithubActionsRenderError> {
    serde_json::from_str(value).map_err(|_| GithubActionsRenderError::InvalidRequest)
}


    #[test]
    fn strict_request_parser_rejects_unknown_and_duplicate_fields() -> Result<(), String> {
        let valid = serde_json::to_string(&request())
            .map_err(|error| format!("fixture failed to serialize: {error}"))?;
        assert_eq!(
            parse_github_actions_render_request(&valid),
            Ok(request()),
            "the versioned request must parse before any rendering"
        );

        let unknown = valid.replacen(
            r#"{"schemaVersion":"#,
            r#"{"permissions":{"contents":"write"},"schemaVersion":"#,
            1,
        );
        assert_eq!(
            parse_github_actions_render_request(&unknown),
            Err(GithubActionsRenderError::InvalidRequest),
            "unknown authority-bearing fields must fail closed"
        );

        let duplicate = valid.replacen(
            r#"{"schemaVersion":"#,
            r#"{"schemaVersion":"steward/github-actions-render-request/v1","schemaVersion":"#,
            1,
        );
        assert_eq!(
            parse_github_actions_render_request(&duplicate),
            Err(GithubActionsRenderError::InvalidRequest),
            "duplicate JSON members must never choose a winner"
        );

        let duplicate_nested_member = valid.replacen(
            r#""repository":"example-org/example-repository""#,
            r#""repository":"example-org/first","repository":"example-org/example-repository""#,
            1,
        );
        assert_eq!(
            parse_github_actions_render_request(&duplicate_nested_member),
            Err(GithubActionsRenderError::InvalidRequest),
            "duplicate members in nested authority-bearing objects must fail closed"
        );
        Ok(())
    }


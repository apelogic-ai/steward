    #[test]
    fn strict_yaml_validation_rejects_duplicates_aliases_merge_keys_and_drift() -> Result<(), String>
    {
        let request = request();
        let context = context();
        let rendered = render_github_actions_workflow(&request, &context)
            .map_err(|error| format!("reviewed request failed to render: {error}"))?;
        assert_eq!(
            validate_generated_github_actions_yaml(&rendered.yaml, &request, &context),
            Ok(()),
            "the canonical generated workflow must pass the strict parser"
        );

        let duplicate = rendered.yaml.replacen(
            "name: Steward governed GitHub file read",
            "name: first\nname: second",
            1,
        );
        assert_eq!(
            validate_generated_github_actions_yaml(&duplicate, &request, &context),
            Err(GithubActionsRenderError::InvalidGeneratedWorkflow)
        );

        let alias = rendered.yaml.replacen(
            "permissions: {}",
            "permissions: &permissions {}\nalias: *permissions",
            1,
        );
        assert_eq!(
            validate_generated_github_actions_yaml(&alias, &request, &context),
            Err(GithubActionsRenderError::InvalidGeneratedWorkflow)
        );

        let merge = rendered.yaml.replacen(
            "permissions: {}",
            "permissions: {}\n<<: {permissions: {}}",
            1,
        );
        assert_eq!(
            validate_generated_github_actions_yaml(&merge, &request, &context),
            Err(GithubActionsRenderError::InvalidGeneratedWorkflow)
        );

        let ambiguous = rendered.yaml.replacen("'on':", "on:", 1).replacen(
            "workflow_dispatch:",
            "workflow_dispatch: yes",
            1,
        );
        assert_eq!(
            validate_generated_github_actions_yaml(&ambiguous, &request, &context),
            Err(GithubActionsRenderError::InvalidGeneratedWorkflow)
        );
        Ok(())
    }

    #[test]
    fn rendering_rejects_invalid_context_and_authority_outside_the_envelope() {
        let mut unreviewed_context = context();
        unreviewed_context.reviewed_release.workflow_commit = "main".to_owned();
        assert_eq!(
            render_github_actions_workflow(&request(), &unreviewed_context),
            Err(GithubActionsRenderError::UnreviewedRelease),
            "a mutable server-side release configuration must not bless a request"
        );

        let mut outside_envelope = context();
        outside_envelope.allowed_task_templates.clear();
        assert_eq!(
            render_github_actions_workflow(&request(), &outside_envelope),
            Err(GithubActionsRenderError::UnsupportedEnvelopeAuthority),
            "a supported template still requires an authoritative envelope fit decision"
        );

        let mut invalid_repository = request();
        invalid_repository.task_template.repository = "example-org/repository/extra".to_owned();
        assert_eq!(
            render_github_actions_workflow(&invalid_repository, &context()),
            Err(GithubActionsRenderError::InvalidRepository)
        );
    }
